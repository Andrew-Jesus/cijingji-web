/**
 * 构建号 —— 全站唯一的那个"现在跑的是哪一次构建"
 *
 * ── ⚠️ 它和「版本号」是两件事，别混（2026-09-30 更正）──────────
 * 本文件只负责那个**构建号**：
 *
 *   · **构建号**（下面的 `BUILD_ID`）= 每次部署都变（线上取 commit sha 前 7 位）。
 *     要的就是"越敏感越好"：它给**门房的缓存命名**（注册时拼在 `/sw.js?v=` 后面，
 *     见 `ServiceWorkerRegistrar`），一个字符变了就换一个新缓存、
 *     顺手在 `activate` 里删掉旧的 —— 这是"改完页面用户还看到旧的"那道总闸门。
 *
 * ⚠️ 另有一个**版本号**的概念：人写的，**只在"这一版有话说"时才变**，给**更新公告**用。
 *    2026-10-01 按 Andy 的决定**暂缓**了（应用还没对外开放，先不做公告）。
 *    将来要做时，务必记住一条**已经踩过的坑**：
 *    **版本号绝不能建在 `BUILD_ID` 上。** 拿构建号当版本号的话，
 *    推一次"改个错别字"都会弹一次公告，用户很快学会无视它，公告就死了。
 *    两者的需求正好相反，所以必须是两个号、各有各的出处
 *    （当时的做法与三条"不弹"的规则记在 `.workbuddy/memory/2026-09-30.md` §十二）。
 *
 * ⚠️ 本文件早先写过一句"缓存名 / 公告 / 开发者模式三处必须是同一个答案"，
 *    那是**错的**（2026-09-30 更正）。真正该守的规矩是：
 *    **每一个号各自只有一个出口**。同一个号写两份的话，会出现
 *    "缓存换了、界面上还是旧的"这类最难查的鬼故事 —— 因为每一处单独看都是对的。
 *
 * ── 值从哪来（由 `next.config.ts` 的 `env` 在**构建期**注入）──────
 *   · 线上（Vercel）：`VERCEL_GIT_COMMIT_SHA` 前 7 位 —— 每次推送都不同，天然唯一；
 *   · 本机构建：构建那一刻的时间戳（本机没有 commit sha 可用）。
 *
 * ⚠️ 它必须是一个**构建期就固定下来的字符串常量**。
 * 别改成在运行时算（比如 `Date.now()`）：服务端渲染与客户端水合会拿到两个不同的值，
 * 那是一个**必然触发**的水合不一致 —— 而且症状是随机的，很难归因到这一行。
 *
 * ⚠️ 本地（含 `next dev`）拿到的是一个**时间戳**而不是 commit 号 —— 本机没有 sha 可算。
 * 这不影响任何事：门房在开发环境**根本不注册**（见 `ServiceWorkerRegistrar`），
 * 这个值在那里只会被开发者模式显示出来而已。
 *
 * 末尾那个 `"dev"` 兜底只在"环境没走到 `next.config.ts`"时才会出现
 * （例如单测直接 import 本模块）—— 有它是为了让类型是 `string` 而不是 `string | undefined`。
 */
export const BUILD_ID = process.env.NEXT_PUBLIC_BUILD_ID ?? "dev";

