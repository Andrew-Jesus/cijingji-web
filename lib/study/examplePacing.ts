/**
 * 例句的**展示节拍** —— 纯函数，可单测。
 *
 * 背景：例句是"提前写"的（用户翻到新卡的那一刻就在后台生成好，见学习页文件头），
 * 所以等他答完题去取，往往**早就写好了**，整个取回过程只要几毫秒。
 * 如果就这么"啪"地把句子端上去，反而显得敷衍 —— 用户会觉得"你根本没在写"。
 *
 * 所以定一个**最短演出时长**：不管真实有多快，都先把这段时间走完再呈现。
 * 快的时候不会一闪而过，慢的时候也不会突然卡住 —— 用户感受到的是同一个节拍，
 * 而不是忽快忽慢的抽奖。
 *
 * 为什么写在这里、而不是写死在组件里：这是一条**产品决策**，不是实现细节。
 * 落到纯函数上，它就有了测试 —— 以后谁想顺手改（比如图快改成 0）会先看到那些断言。
 */

/** 例句最短演出时长（毫秒）。1 秒是权衡：再长就变成真的在浪费用户时间了 */
export const EXAMPLE_MIN_SHOW_MS = 1000;

/**
 * 还需要**再等**多久（毫秒）才能呈现。
 *
 * @param elapsedMs 真实已经花掉的时间（缓存命中时通常是个位数毫秒）
 * @param minShowMs 最短演出时长。留成参数是为了让测试传小值免等
 *
 * 已经等够了就返回 0 —— 下限是 **floor（保底），不是加法**：
 * 真的慢了 3 秒，就不该再补 1 秒变成 4 秒。
 *
 * 脏输入（NaN、负数）一律按"不用等"处理：
 * 这个函数的失败方向必须是**不拖慢用户**，宁可少演一会儿。
 */
export function examplePacingDelayMs(
  elapsedMs: number,
  minShowMs: number = EXAMPLE_MIN_SHOW_MS,
): number {
  // 负数耗时当脏数据处理：那意味着时钟异常（正常不可能"还没开始就已经过了 -100ms"）。
  // 出现这种值时**不补演**，直接放行 —— 这个函数的失败方向永远是不拖慢用户。
  if (!Number.isFinite(elapsedMs) || elapsedMs < 0) return 0;
  if (!Number.isFinite(minShowMs) || minShowMs <= 0) return 0;

  const remaining = minShowMs - elapsedMs;
  return remaining > 0 ? remaining : 0;
}
