/**
 * 用户层行的**编号规则** —— 全工程只有这一处
 *
 * ── 为什么要单独一个文件（2026-09-28）────────────────────────
 * 编号规则原来散在 `studyRepo.ts` 里（生成时用）与 `local.ts` 的升级事务里（迁移时用）。
 * 两处各写一遍必然分叉：改了生成规则忘了改迁移，存量数据的编号就永远留在旧格式上，
 * 表现为"升级完看着好好的，一同步就撞主键"。
 * 放到一个不依赖任何东西的小文件里，两边 import 同一份 —— 这条路径就被堵死了。
 *
 * 这里**不许出现任何 import**：`local.ts` 要 import 它，而 `local.ts` 是数据库本体，
 * 一旦它依赖别的模块就很容易绕成环（Dexie 的单例会在环里被读到 `undefined`）。
 *
 * ── 为什么编号里必须带 userId ────────────────────────────────
 * 任务单和例句的 id 都是**主键**（本地与云端都是）。
 *
 * 原来任务单只由日期决定（`plan:<日期>`）、例句只由词和兴趣决定（`ex:<词>:<兴趣>`），
 * 单人单机时没问题。**同一台设备上两个账号**各有"今天的任务单"时，
 * 两条 id 一模一样，于是：
 *   · 本地 `put` —— 后写的顶掉先写的（A 的进度看着看着变成了 B 的）
 *   · 推上云 —— 撞云端主键，**整批 upsert 被拒**，同步静默失败
 * 两者都不报错，用户只会觉得"数据不对劲"或"同步没生效"。
 *
 * 把主人写进编号里，两条就自然分开了。
 */

/**
 * 任务单编号：一个人一天一份。
 *
 * **显式传 `userId`，不在函数内部读"当前是谁"** ——
 * 读全局状态会让它变成"看着是纯函数、其实有副作用"，
 * 单测就没法直接喂两组主人来验"不撞号"。
 */
export function planIdFor(planDate: string, userId: string): string {
  return `plan:${userId}:${planDate}`;
}

/**
 * 例句编号：一个人 + 一个词 + 一种兴趣 = 一条
 * （生成它是为了按兴趣改写例句，所以兴趣也是键的一部分）。
 *
 * 表上还有 `[user_id+word_id+interest_tag]` 唯一索引兜底，两处口径保持一致。
 */
export function exampleIdFor(wordId: string, interestTag: string, userId: string): string {
  return `ex:${userId}:${wordId}:${interestTag}`;
}
